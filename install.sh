#!/bin/bash
#
# install.sh — configure + build MOSE for NVIDIA GPUs (nvfortran: OpenACC + CUDA-Fortran, MPI, TecIO).
#
# Reference build (the recipe of the md5-gated binaries):
#   ./install.sh build --production
#
# A build with overrides (e.g. V100 arch, 9-species mechanism):
#   ./install.sh build --master=None --gpu-arch=cc70,cuda12.6 --nsc=9 --nrans=2
#
# Incremental rebuild after a configure (reuses the build dir, no reconfigure):
#   ./install.sh compile
#
set -e  # exit on any command failure
set -u  # treat unset variables as an error

PROGRAM=$(basename "$0")
readonly DIR=$(pwd)
VERBOSE=false
project=MOSE

# -------- global defaults --------
COMMAND=""
MASTER_TYPE=""
USE_OPENMP="false"
USE_MPI="true"
USE_TECIO="true"
USE_SUNDIALS="false"
USE_CANTERA="false"
REMOTE="false"
BUILD_TYPE="RELEASE"
JOBS="8"
NO_CLEAN="false"
BUILD_DIR=""          # default: build/

# -------- GPU defaults = the canonical production configuration --------
GPU_ARCH="cc80,cuda12.6"   # A30=cc80, V100=cc70; append ,cudaX.Y on a driverless host
MOSE_NSC="4"               # species count (Frolov = 4)
MOSE_NRANS="2"             # RANS variable count (SST = 2)
ODE_RODAS="OFF"            # GPU chemistry integrator: OFF = radau5_dev (production), ON = rodas_dev (device RODAS4)
FFLAGS=""                  # CMAKE_Fortran_FLAGS (set by --production)
NVHPC_ROOT="${NVHPC_ROOT:-/opt/share/libs/nvidia/hpc_sdk/Linux_x86_64/24.11}"

function usage() {
    cat <<EOF

Install / build script for $project

Usage:
  $PROGRAM [GLOBAL_OPTIONS] COMMAND [COMMAND_OPTIONS]

Global Options:
  -h, --help        Show this help and exit
  -v, --verbose     Enable verbose output

Commands:
  build             Clean configure + build
    --master=<name>       Master (None, hydra)                [required]
    --use-openmp          Enable OpenMP (hybrid OMP+MPI+ACC)
    --no-mpi              Build without MPI (one GPU)
    --no-tecio            Build without TecIO (no szplt I/O)
    --use-sundials        Enable SUNDIALS
    --use-cantera         Enable Cantera
    --build-dir=<path>    Build directory  (default: build)
    --jobs=<N>            Parallel build jobs                 (default: $JOBS)
    --no-clean            Reuse existing build dir (incremental), skip rm -rf

  GPU build options:
    --production          CERTIFIED production GPU build = the recipe of the md5-gated binaries:
                          --master=None, -gpu=cc70,cc80,cuda12.6,ptxinfo, NSC=7 NRANS=2 (ONERA-7 + SST),
                          radau5_dev, CMAKE_Fortran_FLAGS='-cpp -Mbackslash -tp=x86-64-v3' (generic AVX2 host
                          code: the default -tp=native ties the binary to the build node's CPU). Later options
                          still override (e.g. --nsc=4)
    --gpu-arch=<opts>     -gpu= options   (default: $GPU_ARCH ; V100: cc70)
    --nsc=<N>             MOSE_NSC species count              (default: $MOSE_NSC)
    --nrans=<N>           MOSE_NRANS RANS variables           (default: $MOSE_NRANS)
    --ode-rodas           GPU chemistry with rodas_dev instead of radau5_dev (MOSE_ODE_RODAS)

  Full flag reference: docs/development/build-flags.md

  compile           Incremental build using CMakePresets (no reconfigure)
  update            Download git submodules
    --remote              Use the latest remote commit

EOF
    exit 1
}

log()   { [ "$VERBOSE" = true ] && echo -e "\033[1;90m$1\033[0m" || true; }
error() { echo -e "\033[1;31m[ERROR] $1\033[0m" >&2; }
task()  { echo -e "\033[1;38;5;186m==> $1\033[0m"; }

function write_presets() {
  FC=$(grep '^CMAKE_Fortran_COMPILER:' "$BUILD_DIR/CMakeCache.txt" | cut -d= -f2-)
  CC=$(grep '^CMAKE_C_COMPILER:'       "$BUILD_DIR/CMakeCache.txt" | cut -d= -f2-)
  CXX=$(grep '^CMAKE_CXX_COMPILER:'    "$BUILD_DIR/CMakeCache.txt" | cut -d= -f2-)
  cat <<EOF > CMakePresets.json
{
  "version": 3,
  "cmakeMinimumRequired": { "major": 3, "minor": 23 },
  "configurePresets": [
    {
      "name": "default",
      "description": "Generated by install.sh",
      "binaryDir": "${BUILD_DIR}",
      "cacheVariables": {
        "MASTER": "${MASTER_TYPE}",
        "CMAKE_BUILD_TYPE": "${BUILD_TYPE}",
        "CMAKE_Fortran_COMPILER": "${FC}",
        "CMAKE_C_COMPILER": "${CC}",
        "CMAKE_CXX_COMPILER": "${CXX}",
        "USE_TECIO": "${USE_TECIO}",
        "USE_SUNDIALS": "${USE_SUNDIALS}",
        "USE_CANTERA": "${USE_CANTERA}",
        "USE_OPENMP": "${USE_OPENMP}",
        "USE_MPI": "${USE_MPI}",
        "USE_OPENACC": "ON",
        "OPENACC_GPU_OPTS": "${GPU_ARCH}",
        "MOSE_NSC": "${MOSE_NSC}",
        "MOSE_NRANS": "${MOSE_NRANS}"
      }
    }
  ]
}
EOF
}

# -------- parse global options --------
while getopts "hv-:" opt; do
    case "$opt" in
        -) case "$OPTARG" in
               verbose) VERBOSE=true ;;
               help) usage ;;
               *) error "Unknown global option '--$OPTARG'"; usage ;;
           esac ;;
        h) usage ;;
        v) VERBOSE=true ;;
        ?) error "Unknown global option '-$OPTARG'"; usage ;;
    esac
done
shift $((OPTIND -1))

[[ $# -eq 0 ]] && { error "No command provided!"; usage; }
COMMAND="$1"; shift
case "$COMMAND" in build|compile|update) ;; *) error "Unknown command '$COMMAND'"; usage ;; esac

# -------- parse command options --------
while [[ $# -gt 0 ]]; do
    case "$1" in
        --master=*)      MASTER_TYPE="${1#*=}" ;;
        --use-openmp)    USE_OPENMP="true" ;;
        --no-mpi)        USE_MPI="false" ;;
        --no-tecio)      USE_TECIO="false" ;;
        --use-sundials)  USE_SUNDIALS="true" ;;
        --use-cantera)   USE_CANTERA="true" ;;
        --build-dir=*)   BUILD_DIR="${1#*=}" ;;
        --jobs=*)        JOBS="${1#*=}" ;;
        --no-clean)      NO_CLEAN="true" ;;
        # ---- GPU ----
        --production)    MASTER_TYPE="None"; USE_MPI="true"; USE_TECIO="true"
                         GPU_ARCH="cc70,cc80,cuda12.6,ptxinfo"; MOSE_NSC="7"; MOSE_NRANS="2"; ODE_RODAS="OFF"
                         FFLAGS="-cpp -Mbackslash -tp=x86-64-v3" ;;
        --gpu-arch=*)    GPU_ARCH="${1#*=}" ;;
        --nsc=*)         MOSE_NSC="${1#*=}" ;;
        --nrans=*)       MOSE_NRANS="${1#*=}" ;;
        --ode-rodas)     ODE_RODAS="ON" ;;
        --remote)        REMOTE="true" ;;
        -v|--verbose)    VERBOSE=true ;;
        *) error "Unknown option '$1' for command '$COMMAND'"; usage ;;
    esac
    shift
done

[[ -z "$BUILD_DIR" ]] && BUILD_DIR="$DIR/build"

case "$COMMAND" in
    build)
        task "Building $project"
        [[ -z "$MASTER_TYPE" ]] && { error "--master is required (None or hydra)"; exit 1; }

        if [[ $MASTER_TYPE == "None" ]]; then
          task "Cloning submodules"
          git submodule update --init lib/* || true
          git submodule update --init --recursive lib/third_party/FiNeR || true
        fi

        # the compilers: nvhpc
        [[ -d "$NVHPC_ROOT" ]] && export PATH="$NVHPC_ROOT/compilers/bin:$NVHPC_ROOT/comm_libs/mpi/bin:$PATH"
        export FC=nvfortran CC=nvc CXX=nvc++

        GPU_ARGS=(-DUSE_OPENACC=ON -DOPENACC_GPU_OPTS="$GPU_ARCH"
                  -DMOSE_NSC="$MOSE_NSC" -DMOSE_NRANS="$MOSE_NRANS" -DMOSE_ODE_RODAS="$ODE_RODAS")
        # MPI: point CMake at the HPC-X wrappers and nothing else (the MPI_*_WORKS=TRUE shortcut makes a fresh
        # configure stop in FindMPI on this cluster; without it the configure completes, tested 2026-09-28).
        MPI_ARGS=()
        if [[ "$USE_MPI" == "true" ]]; then
          MPI_ARGS=(-DMPI_Fortran_COMPILER="$NVHPC_ROOT/comm_libs/mpi/bin/mpifort" -DMPI_C_COMPILER="$NVHPC_ROOT/comm_libs/mpi/bin/mpicc" -DMPI_CXX_COMPILER="$NVHPC_ROOT/comm_libs/mpi/bin/mpicxx")
        fi

        task "Configuring $project  [dir=$BUILD_DIR  arch=$GPU_ARCH  nsc=$MOSE_NSC nrans=$MOSE_NRANS]"
        [[ "$NO_CLEAN" == "true" ]] || rm -rf "$BUILD_DIR"
        FF_ARGS=(); [[ -n "$FFLAGS" ]] && FF_ARGS=(-DCMAKE_Fortran_FLAGS="$FFLAGS")
        cmake -B "$BUILD_DIR" -DMASTER="$MASTER_TYPE" -DCMAKE_BUILD_TYPE="$BUILD_TYPE" "${FF_ARGS[@]}" \
              -DUSE_TECIO="$USE_TECIO" -DUSE_OPENMP="$USE_OPENMP" -DUSE_MPI="$USE_MPI" \
              -DUSE_SUNDIALS="$USE_SUNDIALS" -DUSE_CANTERA="$USE_CANTERA" \
              "${GPU_ARGS[@]}" "${MPI_ARGS[@]}" || exit 1

        task "Building (target MOSE, -j $JOBS)"
        cmake --build "$BUILD_DIR" -j "$JOBS" --target MOSE || exit 1
        task "[OK] bin/MOSE built"
        write_presets && log "[OK] CMakePresets.json written"
        ;;
    compile)
        task "Incremental compile via CMakePresets"
        cmake --preset default || exit 1
        cmake --build "${BUILD_DIR:-$DIR/build}" -j "$JOBS" --target MOSE || exit 1
        task "[OK] bin/MOSE rebuilt"
        ;;
    update)
        task "Updating git submodules"
        if [[ "$REMOTE" == "true" ]]; then git submodule update --init --remote
        else git submodule update --init; fi
        task "[OK] Submodules updated"
        ;;
esac
